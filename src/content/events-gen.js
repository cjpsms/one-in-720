function makeOption(cat, ev, label, i, evText) {
  const id = `o${i + 1}`;
  const style = styleOf(label, evText);
  const h = hash(ev + label);
  const [good, bad] = END[cat];
  const cost = COST(label);
  const base = { id, label };
  if (cost) base.cost = { money: cost };
  if (style === 'avoid') {
    return { ...base, yes: R({ stress: 1 }, `${label} ${CALM[h % CALM.length]}`) };
  }
  if (style === 'rest') {
    return { ...base, yes: R({ stress: -2, energy: 1 }, `${label} ${EASY[h % EASY.length]}`) };
  }
  if (style === 'spend') {
    return { ...base, cost: { money: cost || 40 }, yes: R({ peer: 2, stress: -2 }, `${label} ${good[h % 2]}`) };
  }
  const s = STYLES[style];
  const kind = style === 'join' && cat !== 'หอพัก ยามค่ำคืน' && cat !== 'หอพัก ชีวิตประจำวัน' ? 'skip' : OFFENCE[style];
  return {
    ...base, ok: s.ok, odds: s.odds,
    yes: { fx: s.yes.fx, log: `${label} ${good[h % 2]}`, ...s.yesX },
    no: { fx: s.no.fx, log: `${label} แต่${bad[h % 2]}`, ...s.noX, ...(kind ? { offend: kind } : {}) },
  };
}

export const SCENES_G = EVENTS.map(([id, cat, text, labels]) => {
  const c = CAT[cat] || { places: SOC };
  return sc(`ev_${id}`, {
    places: c.places, grades: c.grades || [1, 6], w: c.phase ? (ctx) => (ctx.phase ? 2 : 0.5) : 1,
    title: cat, text: () => text,
    options: labels.map((l, i) => makeOption(cat, id, l, i, text)),
  });
});
