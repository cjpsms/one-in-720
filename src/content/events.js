// ctx (from the engine): { grade, place: 'dorm'|'class'|'canteen'|'home'|'weekend', stats, day }
//   stats uses the view() keys (health, energy, stress, knowledge, peer, teacherTrust, money ...). PLACEHOLDER: all
//   stats except money are read as 0-100, so the numbers below are on that scale.
//   Optional extras the events use when present: ctx.phase ('midterm'|'final'|'results'), ctx.recent (event ids seen
//   lately, they get a lower weight), ctx.friendNames (array of names), ctx.teacherName, ctx.teacherMood,
//   ctx.eventChance (overrides EVENT_CONFIG.baseChance), ctx.vars (see below).
//
// Names inside the text (friends, the teacher, a dish) are rolled once by pickEvent and stored in `event.vars`
// (plain JSON). The engine saves { id, vars } with its pending and rebuilds the event after a load with
// restoreEvent(id, vars). event.text(ctx) and option.apply(ctx, rng) work with or without ctx.vars.
//
// option.apply(ctx, rng) -> { fx: { health, stress, energy, knowledge, peer, teacherTrust, money }, log, ending? }
//   fx only has the keys that change. A money loss is capped at ctx.stats.money (never goes below 0).
//   In EVENTS (the raw table) an option label may be a function of ctx; events returned by pickEvent/restoreEvent
//   always have plain string labels.
//   An option may carry `cost` (a rough baht cost) so the UI can grey it out; apply always stays safe.

