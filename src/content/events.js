const V = (ctx) => ({ ...DEFAULT_VARS, ...((ctx && ctx.vars) || {}) });
const S = (ctx, key, d = 50) => (ctx && ctx.stats && Number.isFinite(ctx.stats[key]) ? ctx.stats[key] : d);
const clamp01 = (x) => Math.max(0, Math.min(1, x));

// ---- building blocks -------------------------------------------------------------------------------------------

const num = (x, ctx) => (typeof x === 'function' ? x(ctx) : x);
const str = (x, ctx) => (typeof x === 'function' ? x(V(ctx), ctx) : x);

// fx spec values are a number or [lo, hi] (rolled with rng, one decimal)
function rollFx(spec, rng) {
  const out = {};
  for (const k of Object.keys(spec || {})) {
    const s = spec[k];
    let v;
    if (Array.isArray(s)) v = Math.round((s[0] + rng.float() * (s[1] - s[0])) * 10) / 10;
    else v = s;
    if (v) out[k] = v;
  }
  return out;
}

function addFx(a, b) {
  for (const k of Object.keys(b)) {
    const v = Math.round(((a[k] || 0) + b[k]) * 10) / 10;
    if (v) a[k] = v;
    else delete a[k];
  }
}

// spec: { fx, log, risk?: { p, fx, log }, branch?: { p, yes: {fx, log}, no: {fx, log} }, cost? }
// risk adds extra fx and a second log sentence with probability p; branch replaces fx/log by yes/no.
function opt(id, label, sub, spec) {
  const o = {
    id,
    label,
    apply(ctx, rng) {
      let base = spec;
      if (spec.branch) base = rng.chance(clamp01(num(spec.branch.p, ctx))) ? spec.branch.yes : spec.branch.no;
      const fx = rollFx(base.fx, rng);
      let log = str(base.log, ctx);
      if (spec.risk && rng.chance(clamp01(num(spec.risk.p, ctx)))) {
        addFx(fx, rollFx(spec.risk.fx, rng));
        log = `${log} ${str(spec.risk.log, ctx)}`;
      }
      if (fx.money < 0 && ctx && ctx.stats && Number.isFinite(ctx.stats.money)) {
        fx.money = -Math.min(-fx.money, Math.max(0, ctx.stats.money));
        if (!fx.money) delete fx.money;
      }
      const out = { fx, log };
      if (spec.ending) out.ending = spec.ending;
      return out;
    },
  };
  if (sub) o.sub = sub;
  if (spec.cost) o.cost = spec.cost;
  return o;
}

// def: { grades, places, w (number or fn(ctx)), title, text(v, ctx), options }
function ev(id, def) {
  return {
    id,
    grades: def.grades || [1, 6],
    places: def.places,
    weight: (ctx) => {
      let w = typeof def.w === 'function' ? def.w(ctx) : def.w;
      if (!(w > 0)) return 0;
      if (ctx && Array.isArray(ctx.recent) && ctx.recent.includes(id)) w *= EVENT_CONFIG.recentPenalty;
      return w;
    },
    title: def.title,
    text: (ctx) => def.text(V(ctx), ctx),
    options: def.options,
  };
}

