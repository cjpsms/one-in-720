// ---- picking ---------------------------------------------------------------------------------------------------

export function eventById(id) {
  return EVENTS.find((e) => e.id === id) || null;
}

// A copy of the event whose text/apply use these vars unless the engine passes its own ctx.vars.
function bind(event, vars) {
  const withVars = (c) => ({ ...c, vars: (c && c.vars) || vars });
  return {
    ...event,
    vars,
    text: (c) => event.text(withVars(c)),
    options: event.options.map((o) => {
      // labels may depend on the names, so the bound event always has plain string labels
      const label = typeof o.label === 'function' ? o.label({ vars }) : o.label;
      return { ...o, label, apply: (c, rng) => o.apply(withVars(c), rng) };
    }),
  };
}

// Rebuild a saved event: the engine stores { id, vars } with the pending.
export function restoreEvent(id, vars) {
  const e = eventById(id);
  return e ? bind(e, vars || {}) : null;
}

function rollVars(ctx, rng) {
  const names = Array.isArray(ctx.friendNames) && ctx.friendNames.length >= 2 ? ctx.friendNames : FRIEND_NAMES;
  const friend = rng.pick(names);
  let friend2 = rng.pick(names);
  for (let i = 0; i < 8 && friend2 === friend; i++) friend2 = rng.pick(names);
  return { friend, friend2, teacher: ctx.teacherName || DEFAULT_VARS.teacher, dish: rng.pick(DISHES) };
}

// -> a bound event (with .vars) or null. Deterministic for the same ctx and rng state.
export function pickEvent(ctx, rng) {
  const p = ctx.eventChance ?? EVENT_CONFIG.baseChance;
  if (!rng.chance(p)) return null;
  const pool = [];
  let total = 0;
  for (const e of EVENTS) {
    if (ctx.grade < e.grades[0] || ctx.grade > e.grades[1]) continue;
    if (!e.places.includes(ctx.place)) continue;
    const w = e.weight(ctx);
    if (!(w > 0)) continue;
    pool.push([e, w]);
    total += w;
  }
  if (!pool.length) return null;
  let r = rng.float() * total;
  let chosen = pool[pool.length - 1][0];
  for (const [e, w] of pool) {
    r -= w;
    if (r < 0) {
      chosen = e;
      break;
    }
  }
  return bind(chosen, rollVars(ctx, rng));
}
